package helium314.keyboard.latin.settings

import android.content.Context
import android.content.SharedPreferences
import androidx.core.content.edit
import helium314.keyboard.keyboard.emoji.RecentEmojis
import helium314.keyboard.latin.personalization.PersonalizationHelper
import helium314.keyboard.latin.utils.ExecutorUtils
import helium314.keyboard.latin.utils.prefs
import kotlinx.serialization.Serializable
import kotlinx.serialization.encodeToString
import kotlinx.serialization.json.Json
import java.util.UUID

/**
 * A learning context isolates learned data (user history words and next-word predictions, recent emojis)
 * for a set of apps. Apps that are not part of any context use the default context, whose id is [DEFAULT].
 */
@Serializable
data class LearningContext(val id: String, val name: String, val packages: Set<String> = emptySet())

object LearningContexts {
    /** id of the default context, used by all apps that are not assigned to a custom context */
    const val DEFAULT = ""
    const val PREF_LEARNING_CONTEXTS = "learning_contexts"
    private val ID_REGEX = "[0-9a-f]{8}".toRegex() // as generated by create()

    /** the context used for the app that currently has input focus */
    @Volatile
    var current = DEFAULT
        private set

    private var cachedRaw: String? = null
    private var cachedContexts = emptyList<LearningContext>()

    @Synchronized
    fun getAll(prefs: SharedPreferences): List<LearningContext> {
        val raw = prefs.getString(PREF_LEARNING_CONTEXTS, null)
        if (raw == cachedRaw) return cachedContexts
        cachedContexts = if (raw.isNullOrEmpty()) emptyList()
            // ids end up in file names and pref keys, and prefs can come from a restored backup
            else runCatching { Json.decodeFromString<List<LearningContext>>(raw) }.getOrDefault(emptyList())
                .filter { it.id.matches(ID_REGEX) }
        cachedRaw = raw
        return cachedContexts
    }

    fun get(prefs: SharedPreferences, id: String) = getAll(prefs).firstOrNull { it.id == id }

    @Synchronized
    private fun save(prefs: SharedPreferences, contexts: List<LearningContext>) {
        val raw = if (contexts.isEmpty()) null else Json.encodeToString(contexts)
        prefs.edit { if (raw == null) remove(PREF_LEARNING_CONTEXTS) else putString(PREF_LEARNING_CONTEXTS, raw) }
        cachedRaw = raw
        cachedContexts = contexts
    }

    fun create(prefs: SharedPreferences, name: String): LearningContext {
        val context = LearningContext(UUID.randomUUID().toString().take(8), name.trim())
        save(prefs, getAll(prefs) + context)
        return context
    }

    fun rename(prefs: SharedPreferences, id: String, name: String) =
        save(prefs, getAll(prefs).map { if (it.id == id) it.copy(name = name.trim()) else it })

    /** Sets the apps of context [id]. An app can only be in one context, so it is removed from all others. */
    fun setPackages(prefs: SharedPreferences, id: String, packages: Set<String>) =
        save(prefs, getAll(prefs).map {
            if (it.id == id) it.copy(packages = packages) else it.copy(packages = it.packages - packages)
        })

    /** Removes the context and all data learned in it. */
    fun delete(context: Context, id: String) {
        val prefs = context.prefs()
        if (id == DEFAULT) return
        save(prefs, getAll(prefs).filterNot { it.id == id })
        PersonalizationHelper.removeUserHistoryDictionaries(context, id)
        RecentEmojis.clearContext(id)
        if (current == id) current = DEFAULT // the facilitator will reload on the next input start
    }

    /**
     * Removes files of deleted contexts in the background. Deleting a context can not stop a dictionary that is still in use
     * from writing itself to file again, so this is called when the context changes, i.e. when that dictionary is closed.
     */
    fun removeDataOfDeletedContexts(context: Context) {
        val existingIds = getAll(context.prefs()).mapTo(HashSet()) { it.id }
        ExecutorUtils.getBackgroundExecutor(ExecutorUtils.KEYBOARD).execute {
            PersonalizationHelper.removeDictionariesOfDeletedContexts(context, existingIds)
        }
    }

    fun idForPackage(prefs: SharedPreferences, packageName: String?): String {
        if (packageName.isNullOrEmpty()) return DEFAULT
        return getAll(prefs).firstOrNull { packageName in it.packages }?.id ?: DEFAULT
    }

    /**
     * Selects the context for [packageName]. Returns whether this changed the current context.
     * [beforeChange] runs first when it does, while [current] is still the old context.
     */
    @JvmOverloads
    fun setCurrentForPackage(prefs: SharedPreferences, packageName: String?, beforeChange: Runnable? = null): Boolean {
        val id = idForPackage(prefs, packageName)
        if (id == current) return false
        beforeChange?.run()
        current = id
        return true
    }

    /** suffix for names / keys of data that is stored separately per context, empty for the default context */
    fun keySuffix(id: String) = if (id == DEFAULT) "" else "_$id"
}
